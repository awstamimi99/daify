const { chromium } = require('@playwright/test');
const fs = require('node:fs');
const path = require('node:path');
const out = path.join(__dirname, 'evidence/2026-09-12');
(async () => {
  const browser = await chromium.launch();
  const context = await browser.newContext();
  const page = await context.newPage();
  const records = [];
  const record = (check, data) => { records.push({ check, ...data }); fs.writeFileSync(path.join(out, 'prototype-audit.json'), JSON.stringify(records, null, 2)); };
  await page.goto('http://127.0.0.1:8910/dashboard/menu-builder.html?create=item');
  await page.locator('#itemName').fill('QA اختبار طبق');
  await page.locator('#itemPrice').fill('-99 KD');
  await page.locator('#drawerSave').click();
  record('negative-price', { savedInStore: await page.evaluate(() => JSON.stringify(window.MenuFlowStore.getState()).includes('-99 KD')) });
  await page.reload();
  record('same-browser-persistence', { itemRetained: await page.evaluate(() => JSON.stringify(window.MenuFlowStore.getState()).includes('QA اختبار طبق')) });
  await page.goto('http://127.0.0.1:8910/dashboard/publish.html');
  if (await page.locator('#publishBtn').count()) await page.locator('#publishBtn').click();
  await page.goto('http://127.0.0.1:8910/dashboard/publish.html');
  const url = await page.locator('#liveUrl').inputValue();
  const ownerView = await context.newPage();
  await ownerView.goto(url);
  const freshContext = await browser.newContext();
  const guest = await freshContext.newPage();
  await guest.goto(url);
  record('published-link-other-browser', { url, ownerSeesAddedItem: await ownerView.getByText('QA اختبار طبق', { exact: true }).count() > 0, freshGuestSeesAddedItem: await guest.getByText('QA اختبار طبق', { exact: true }).count() > 0 });
  await page.goto('http://127.0.0.1:8910/dashboard/menu-builder.html?create=item');
  await page.locator('#itemName').fill('QA Unsaved dish');
  await page.locator('#itemPrice').fill('5 KD');
  await page.keyboard.press('Escape');
  record('drawer-escape', { remainsOpen: await page.locator('#itemDrawer').evaluate(el => el.classList.contains('open')) });
  await page.locator('#drawerCancel').click();
  record('drawer-unsaved-cancel', { drawerClosedWithoutConfirmation: !(await page.locator('#itemDrawer').evaluate(el => el.classList.contains('open'))) });
  await page.goto('http://127.0.0.1:8910/dashboard/menu-builder.html?create=item');
  await page.locator('#itemName').fill('QA Lost after storage failure');
  await page.locator('#itemPrice').fill('5 KD');
  await page.evaluate(() => { Storage.prototype.setItem = function () { throw new DOMException('QA quota fault', 'QuotaExceededError'); }; });
  await page.locator('#drawerSave').click();
  const accepted = await page.evaluate(() => JSON.stringify(window.MenuFlowStore.getState()).includes('QA Lost after storage failure'));
  const claimedSuccess = await page.getByText('Dish added', { exact: true }).count() > 0;
  await page.reload();
  record('storage-quota-failure', { acceptedInMemory: accepted, claimedSuccess, lostAfterReload: !(await page.evaluate(() => JSON.stringify(window.MenuFlowStore.getState()).includes('QA Lost after storage failure'))) });
  await freshContext.close(); await context.close(); await browser.close();
  console.log(JSON.stringify(records, null, 2));
})().catch(e => { console.error(e); process.exit(1); });
